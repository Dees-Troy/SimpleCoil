package com.mousebird.maply;

public class Point3d {
    public double x;
    public double y;
    public double z;

    public Point3d() {
        this.x = 0;
        this.y = 0;
        this.z = 0;
    }

    public Point3d(double x, double y, double z) {
        this.x = x;
        this.y = y;
        this.z = z;
    }
}
